#!/usr/bin/env python3
"""Generates `src/entity_data.rs` from WHATWG's `entities.json`.

The table holds the named character references **with the trailing
semicolon** (the spec's 25 legacy non-`&;` aliases are left unsupported:
`decode_entities` keeps them verbatim). Sorted by name for binary search;
values are codepoints (some references expand to two characters).

Stdlib only; fetches `entities.json` (into `target/`, gitignored) when
absent. Run after the spec updates a release:

    scripts/generate_entities.py
"""

import json
import pathlib
import sys
import urllib.request

URL = "https://html.spec.whatwg.org/entities.json"
CACHE = pathlib.Path("target/entities.json")
OUT = pathlib.Path("src/entity_data.rs")


def table() -> dict:
    if not CACHE.exists():
        CACHE.parent.mkdir(exist_ok=True)
        print(f"fetching {URL}")
        urllib.request.urlretrieve(URL, CACHE)
    raw = json.loads(CACHE.read_text())
    return {key[1:]: value["codepoints"] for key, value in raw.items() if key.endswith(";")}


def main() -> None:
    entities = table()
    names = sorted(entities)
    out = [
        "// Generated by `scripts/generate_entities.py` from WHATWG's"
        " `entities.json`",
        "// (semicolon forms only; the legacy non-`&;` aliases are"
        " unsupported). Do not edit:",
        "// regenerate instead.",
        "/// The named character references by name (`&` and `;` excluded),",
        "/// sorted, to their codepoints.",
        "pub(crate) static ENTITIES: &[(&str, &[u32])] = &[",
    ]
    for name in names:
        points = entities[name]
        codes = ", ".join(str(code) for code in points)
        out.append(f'    ("{name}", &[{codes}]),')
    out.append("];")
    out.append(
        f"/// The longest name (the decode's scan bound, `&` and `;`"
        f" included).\n"
        f"pub(crate) const MAX_REFERENCE: usize = {max(len(name) for name in names) + 2};"
    )
    OUT.write_text("\n".join(out) + "\n")
    print(f"{OUT}: {len(names)} entities")


if __name__ == "__main__":
    sys.exit(main())
